#[renox::test]
async fn where_in_with_a_large_list_of_text() {
    let app = app().await;
    label(&app, "01JA", "first").await;
    label(&app, "01JB", "second").await;
    label(&app, "01JC", "third").await;
    // Over a thousand values go as one JSON array, for text as for numbers.
    let mut codes: Vec<String> = (0..1500).map(|i| format!("X{i:05}")).collect();
    codes.push("01JA".into());
    codes.push("01JC".into());
    let found = Label::query()
        .where_in("code", codes)
        .order_by("code")
        .get(app.db())
        .await
        .unwrap();
    let names: Vec<&str> = found.iter().map(|l| l.name.as_str()).collect();
    assert_eq!(names, ["first", "third"]);
    // A list that isn't all text (here a NULL in it) can't go as one array:
    // plain placeholders, same answer.
    let mut mixed: Vec<renox::db::DbValue> = (0..1200)
        .map(|i| renox::db::DbValue::Text(format!("Y{i}")))
        .collect();
    mixed.push(renox::db::DbValue::Null);
    mixed.push(renox::db::DbValue::Text("01JB".into()));
    let found = Label::query()
        .where_in("code", mixed)
        .get(app.db())
        .await
        .unwrap();
    assert_eq!(found.len(), 1);
}

#[renox::test]
async fn not_like_ignores_case_offset_works_alone() {
    let app = app().await;
    label(&app, "a", "Coffee").await;
    label(&app, "b", "tea").await;
    label(&app, "c", "COCOA").await;
    let rest = Label::query()
        .where_op("name", "not like", "co%")
        .get(app.db())
        .await
        .unwrap();
    assert_eq!(rest.len(), 1, "{rest:?}");
    assert_eq!(rest[0].name, "tea");
    let skipped = Label::query()
        .order_by("code")
        .offset(1)
        .get(app.db())
        .await
        .unwrap();
    let codes: Vec<&str> = skipped.iter().map(|l| l.code.as_str()).collect();
    assert_eq!(codes, ["b", "c"]);
}

#[renox::test]
async fn aggregates_and_updates_refuse_unknown_columns() {
    let app = app().await;
    let db = app.db();
    let q = || Label::query();
    assert!(
        q().sum::<i64, _>(db, "price; DROP TABLE labels")
            .await
            .is_err()
    );
    assert!(q().avg(db, "nope").await.is_err());
    assert!(q().min::<i64, _>(db, "nope").await.is_err());
    assert!(q().max::<i64, _>(db, "nope").await.is_err());
    assert!(q().increment(db, "nope", 1).await.is_err());
    assert!(q().update(db, &[("nope", &"x")]).await.is_err());
    assert!(
        q().where_in_query("id", BareRow::query(), "nope")
            .get(db)
            .await
            .is_err()
    );
    // The table is still there.
    assert_eq!(q().count(db).await.unwrap(), 0);
}

#[renox::test]
async fn model_edge_cases() {
    let app = app().await;
    let db = app.db();
    // A model with only an id inserts DEFAULT VALUES.
    let bare = BareRow::create(db, BareRow::default()).await.unwrap();
    assert!(bare.id > 0);
    // Upsert needs a conflict target; with nothing to update it skips.
    let err = Label::upsert(db, vec![Label::default()], &[], &[])
        .await
        .unwrap_err();
    assert!(format!("{err:?}").contains("upsert needs at least one `unique_by` column"));
    label(&app, "x", "Original").await;
    Label::upsert(
        db,
        vec![Label {
            code: "x".into(),
            name: "Changed".into(),
            ..Default::default()
        }],
        &["code"],
        &[],
    )
    .await
    .unwrap();
    let kept = Label::query()
        .where_eq("code", "x")
        .first(db)
        .await
        .unwrap()
        .unwrap();
    assert_eq!(kept.name, "Original");
    assert_eq!(Label::insert_many(db, Vec::new()).await.unwrap(), 0);
    // save_only on a row that was never saved is refused; on a row deleted
    // meanwhile it's a 404.
    let mut unsaved = Label::default();
    assert!(unsaved.save_only(db, &["name"]).await.is_err());
    let mut gone = label(&app, "g", "Gone").await;
    renox::db::sql("DELETE FROM labels WHERE id = ?")
        .bind(gone.id)
        .execute(db)
        .await
        .unwrap();
    gone.name = "Back".into();
    assert!(matches!(
        gone.save_only(db, &["name"]).await,
        Err(Error::NotFound)
    ));
}

