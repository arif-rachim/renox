#[derive(Model, serde::Serialize, Default, Clone, Debug)]
#[model(table = "labels")]
struct Label {
    id: i64,
    code: String,
    name: String,
}

#[derive(Model, serde::Serialize, Default, Clone, Debug)]
#[model(table = "bare_rows")]
struct BareRow {
    id: i64,
}

#[derive(Model, serde::Serialize, Default, Clone, Debug)]
#[model(table = "notes", hooks)]
struct Note {
    id: i64,
    label_id: i64,
    body: String,
}

static SAVED: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);

// Only `saved` is overridden: `saving`, `deleting` and `deleted` keep their
// defaults.
impl renox::db::ModelHooks for Note {
    async fn saved(&self, _creating: bool) -> Result {
        SAVED.fetch_add(1, std::sync::atomic::Ordering::SeqCst);
        Ok(())
    }
}

async fn app() -> TestApp {
    let app = TestApp::new(App::new().module(Auth::new())).await;
    let id = match app.db().dialect() {
        Dialect::Postgres => "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        _ => "INTEGER PRIMARY KEY",
    };
    for statement in [
        format!("CREATE TABLE labels (id {id}, code TEXT NOT NULL UNIQUE, name TEXT NOT NULL)"),
        format!("CREATE TABLE bare_rows (id {id})"),
        format!("CREATE TABLE notes (id {id}, label_id BIGINT NOT NULL, body TEXT NOT NULL)"),
    ] {
        renox::db::sql(statement).execute(app.db()).await.unwrap();
    }
    app
}

